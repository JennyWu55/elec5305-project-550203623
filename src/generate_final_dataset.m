function generate_final_dataset()
% ELEC5305 Final Project
% Controlled LibriSpeech + DEMAND mixture generator
%
% Input:
%   data/selected/clean/*.flac
%   data/selected/noise/*.wav
%
% Experimental design:
%   4 clean utterances
%   x 2 DEMAND noise environments
%   x 4 SNR conditions (-5, 0, 5, 10 dB)
%   = 32 paired experiments
%
% Each experiment produces:
%   clean.wav
%   noisy.wav
%   wiener.wav
%
% A one-second initial calibration region is added:
%   clean reference = silence during this region
%   noisy signal    = environmental noise only
%
% This allows practical Wiener noise-PSD estimation using an
% initial noise-only segment, while keeping clean/noisy/enhanced
% signals temporally aligned.
%
% Output:
%   data/mixtures/exp_001/...
%   data/mixtures/mixture_metadata.csv

close all;
clc;

%% ============================================================
%  1. Project paths
% =============================================================

thisFile = mfilename('fullpath');
srcDir = fileparts(thisFile);
projectDir = fileparts(srcDir);

cleanDir = fullfile( ...
    projectDir, ...
    'data', ...
    'selected', ...
    'clean');

noiseDir = fullfile( ...
    projectDir, ...
    'data', ...
    'selected', ...
    'noise');

mixtureDir = fullfile( ...
    projectDir, ...
    'data', ...
    'mixtures');

if ~exist(mixtureDir, 'dir')
    mkdir(mixtureDir);
end

fprintf('\n');
fprintf('====================================================\n');
fprintf('ELEC5305 FINAL CONTROLLED DATASET GENERATION\n');
fprintf('====================================================\n');

%% ============================================================
%  2. Fixed experimental parameters
% =============================================================

targetFs = 16000;

snrLevels = [-5 0 5 10];

% Initial noise-only region
calibrationDuration = 1.0;

% Wiener/STFT configuration
frameLength = 512;
hopLength = 256;
fftLength = 512;

% Fixed Wiener configuration
gainFloor = 0.12;
smoothingAlpha = 0.70;

% Noise PSD estimated from this subsection of the
% one-second noise-only calibration region
noiseEstimateStart = 0.05;
noiseEstimateEnd = 0.80;

%% ============================================================
%  3. Find selected clean utterances
% =============================================================

cleanFiles = dir( ...
    fullfile(cleanDir, '*.flac'));

if isempty(cleanFiles)
    cleanFiles = dir( ...
        fullfile(cleanDir, '*.wav'));
end

if isempty(cleanFiles)
    error( ...
        'No clean speech files found in data/selected/clean.');
end

fprintf('\nFound %d clean utterances.\n', ...
    length(cleanFiles));

for i = 1:length(cleanFiles)
    fprintf('  %s\n', cleanFiles(i).name);
end

%% ============================================================
%  4. Find selected DEMAND noises
% =============================================================

noiseFiles = dir( ...
    fullfile(noiseDir, '*.wav'));

if isempty(noiseFiles)
    error( ...
        'No DEMAND noise files found in data/selected/noise.');
end

fprintf('\nFound %d environmental noise files.\n', ...
    length(noiseFiles));

for i = 1:length(noiseFiles)
    fprintf('  %s\n', noiseFiles(i).name);
end

%% ============================================================
%  5. Calculate total number of experiments
% =============================================================

numExperiments = ...
    length(cleanFiles) ...
    * length(noiseFiles) ...
    * length(snrLevels);

fprintf('\nTotal experiments to generate: %d\n', ...
    numExperiments);

%% ============================================================
%  6. Allocate metadata
% =============================================================

experimentID = strings(numExperiments, 1);
speakerID = strings(numExperiments, 1);
utteranceID = strings(numExperiments, 1);
noiseType = strings(numExperiments, 1);

targetSNRdB = zeros(numExperiments, 1);
measuredInputSNRdB = zeros(numExperiments, 1);
outputSNRdB = zeros(numExperiments, 1);
snrImprovementdB = zeros(numExperiments, 1);

sampleRate = zeros(numExperiments, 1);

cleanPath = strings(numExperiments, 1);
noisyPath = strings(numExperiments, 1);
wienerPath = strings(numExperiments, 1);

frameLengthColumn = ...
    repmat(frameLength, numExperiments, 1);

hopLengthColumn = ...
    repmat(hopLength, numExperiments, 1);

fftLengthColumn = ...
    repmat(fftLength, numExperiments, 1);

gainFloorColumn = ...
    repmat(gainFloor, numExperiments, 1);

smoothingAlphaColumn = ...
    repmat(smoothingAlpha, numExperiments, 1);

%% ============================================================
%  7. Generate all experiments
% =============================================================

experimentCounter = 0;

for cleanIndex = 1:length(cleanFiles)

    %% --------------------------------------------------------
    % Load clean speech
    % ---------------------------------------------------------

    cleanFullPath = fullfile( ...
        cleanFiles(cleanIndex).folder, ...
        cleanFiles(cleanIndex).name);

    [cleanSpeech, cleanFs] = ...
        audioread(cleanFullPath);

    if size(cleanSpeech, 2) > 1
        cleanSpeech = ...
            mean(cleanSpeech, 2);
    end

    cleanSpeech = ...
        cleanSpeech(:);

    if cleanFs ~= targetFs
        cleanSpeech = ...
            resample( ...
            cleanSpeech, ...
            targetFs, ...
            cleanFs);
    end

    % Remove DC
    cleanSpeech = ...
        cleanSpeech - mean(cleanSpeech);

    % Normalise clean speech consistently
    cleanPeak = ...
        max(abs(cleanSpeech));

    if cleanPeak <= 0
        warning( ...
            'Skipping empty clean file: %s', ...
            cleanFiles(cleanIndex).name);

        continue;
    end

    cleanSpeech = ...
        0.30 * cleanSpeech / cleanPeak;

    %% --------------------------------------------------------
    % Extract LibriSpeech identifiers from filename
    % ---------------------------------------------------------

    [~, cleanBaseName, ~] = ...
        fileparts(cleanFiles(cleanIndex).name);

    nameParts = ...
        split(string(cleanBaseName), '-');

    if length(nameParts) >= 3

        currentSpeakerID = ...
            nameParts(1);

        currentUtteranceID = ...
            string(cleanBaseName);

    else

        currentSpeakerID = ...
            "unknown";

        currentUtteranceID = ...
            string(cleanBaseName);

    end

    %% --------------------------------------------------------
    % Add one second of silence before clean speech
    % ---------------------------------------------------------

    calibrationSamples = ...
        round(calibrationDuration * targetFs);

    cleanReference = [
        zeros(calibrationSamples, 1);
        cleanSpeech
    ];

    speechRegion = ...
        calibrationSamples + 1 : ...
        length(cleanReference);

    speechPower = ...
        mean(cleanReference(speechRegion).^2);

    %% ========================================================
    % Loop through DEMAND noises
    % =========================================================

    for noiseIndex = 1:length(noiseFiles)

        %% ----------------------------------------------------
        % Load environmental noise
        % -----------------------------------------------------

        noiseFullPath = fullfile( ...
            noiseFiles(noiseIndex).folder, ...
            noiseFiles(noiseIndex).name);

        [environmentNoise, noiseFs] = ...
            audioread(noiseFullPath);

        if size(environmentNoise, 2) > 1
            environmentNoise = ...
                environmentNoise(:, 1);
        end

        environmentNoise = ...
            environmentNoise(:);

        if noiseFs ~= targetFs

            environmentNoise = ...
                resample( ...
                environmentNoise, ...
                targetFs, ...
                noiseFs);

        end

        % Remove DC
        environmentNoise = ...
            environmentNoise ...
            - mean(environmentNoise);

        %% ----------------------------------------------------
        % Noise label
        % -----------------------------------------------------

        [~, noiseBaseName, ~] = ...
            fileparts(noiseFiles(noiseIndex).name);

        currentNoiseType = ...
            regexprep( ...
            string(noiseBaseName), ...
            '^demand_', '');

        currentNoiseType = ...
            regexprep( ...
            currentNoiseType, ...
            '_ch\d+$', '');

        %% ----------------------------------------------------
        % Create deterministic noise segment
        %
        % Same utterance/noise pair uses the same environmental
        % segment at every SNR, ensuring a fair comparison.
        % -----------------------------------------------------

        requiredNoiseLength = ...
            length(cleanReference);

        if length(environmentNoise) < requiredNoiseLength

            repeatCount = ...
                ceil( ...
                requiredNoiseLength ...
                / length(environmentNoise));

            environmentNoise = ...
                repmat( ...
                environmentNoise, ...
                repeatCount, ...
                1);

        end

        maxStart = ...
            length(environmentNoise) ...
            - requiredNoiseLength ...
            + 1;

        deterministicOffset = ...
            1 ...
            + mod( ...
            (cleanIndex - 1) * 100003 ...
            + (noiseIndex - 1) * 1009, ...
            maxStart);

        selectedNoise = ...
            environmentNoise( ...
            deterministicOffset : ...
            deterministicOffset ...
            + requiredNoiseLength - 1);

        selectedNoise = ...
            selectedNoise ...
            - mean(selectedNoise);

        %% ----------------------------------------------------
        % Measure noise power only over speech region
        % -----------------------------------------------------

        baseNoisePower = ...
            mean( ...
            selectedNoise(speechRegion).^2);

        if baseNoisePower <= eps
            error( ...
                'Selected environmental noise has almost zero power.');
        end

        %% ====================================================
        % Loop through SNR levels
        % =====================================================

        for snrIndex = 1:length(snrLevels)

            experimentCounter = ...
                experimentCounter + 1;

            currentTargetSNR = ...
                snrLevels(snrIndex);

            currentExperimentID = ...
                sprintf( ...
                'exp_%03d', ...
                experimentCounter);

            fprintf('\n');
            fprintf( ...
                '[%02d/%02d] %s | %s | %+.0f dB\n', ...
                experimentCounter, ...
                numExperiments, ...
                cleanBaseName, ...
                currentNoiseType, ...
                currentTargetSNR);

            %% ------------------------------------------------
            % Scale environmental noise to requested SNR
            % -------------------------------------------------

            noiseScale = ...
                sqrt( ...
                speechPower ...
                / ( ...
                baseNoisePower ...
                * 10^(currentTargetSNR / 10)));

            scaledNoise = ...
                noiseScale * selectedNoise;

            noisySignal = ...
                cleanReference + scaledNoise;

            %% ------------------------------------------------
            % Verify measured input SNR
            % -------------------------------------------------

            inputError = ...
                noisySignal(speechRegion) ...
                - cleanReference(speechRegion);

            measuredInputSNR = ...
                10 * log10( ...
                sum( ...
                cleanReference(speechRegion).^2) ...
                / ...
                (sum(inputError.^2) + eps));

            %% ------------------------------------------------
            % Wiener enhancement
            % -------------------------------------------------

            enhancedSignal = ...
                fixedWienerEnhance( ...
                noisySignal, ...
                targetFs, ...
                frameLength, ...
                hopLength, ...
                fftLength, ...
                noiseEstimateStart, ...
                noiseEstimateEnd, ...
                gainFloor, ...
                smoothingAlpha);

            %% ------------------------------------------------
            % Output SNR
            % -------------------------------------------------

            signalLength = min([ ...
                length(cleanReference), ...
                length(noisySignal), ...
                length(enhancedSignal)]);

            cleanEval = ...
                cleanReference(1:signalLength);

            noisyEval = ...
                noisySignal(1:signalLength);

            enhancedEval = ...
                enhancedSignal(1:signalLength);

            evalStart = min( ...
                calibrationSamples + 1, ...
                signalLength);

            evalRegion = ...
                evalStart:signalLength;

            outputError = ...
                enhancedEval(evalRegion) ...
                - cleanEval(evalRegion);

            currentOutputSNR = ...
                10 * log10( ...
                sum(cleanEval(evalRegion).^2) ...
                / ...
                (sum(outputError.^2) + eps));

            currentSNRImprovement = ...
                currentOutputSNR ...
                - measuredInputSNR;

            %% ------------------------------------------------
            % Create experiment folder
            % -------------------------------------------------

            experimentFolder = ...
                fullfile( ...
                mixtureDir, ...
                currentExperimentID);

            if ~exist(experimentFolder, 'dir')
                mkdir(experimentFolder);
            end

            %% ------------------------------------------------
            % Save triplet with COMMON scaling
            %
            % Do not normalise clean/noisy/Wiener independently.
            % Relative amplitudes must remain meaningful.
            % -------------------------------------------------

            commonPeak = max([ ...
                abs(cleanEval); ...
                abs(noisyEval); ...
                abs(enhancedEval)]);

            if commonPeak < 1
                commonScale = 1;
            else
                commonScale = ...
                    0.98 / commonPeak;
            end

            cleanToSave = ...
                commonScale * cleanEval;

            noisyToSave = ...
                commonScale * noisyEval;

            enhancedToSave = ...
                commonScale * enhancedEval;

            currentCleanFile = ...
                fullfile( ...
                experimentFolder, ...
                'clean.wav');

            currentNoisyFile = ...
                fullfile( ...
                experimentFolder, ...
                'noisy.wav');

            currentWienerFile = ...
                fullfile( ...
                experimentFolder, ...
                'wiener.wav');

            audiowrite( ...
                currentCleanFile, ...
                cleanToSave, ...
                targetFs);

            audiowrite( ...
                currentNoisyFile, ...
                noisyToSave, ...
                targetFs);

            audiowrite( ...
                currentWienerFile, ...
                enhancedToSave, ...
                targetFs);

            %% ------------------------------------------------
            % Metadata
            % -------------------------------------------------

            experimentID(experimentCounter) = ...
                string(currentExperimentID);

            speakerID(experimentCounter) = ...
                string(currentSpeakerID);

            utteranceID(experimentCounter) = ...
                string(currentUtteranceID);

            noiseType(experimentCounter) = ...
                string(currentNoiseType);

            targetSNRdB(experimentCounter) = ...
                currentTargetSNR;

            measuredInputSNRdB(experimentCounter) = ...
                measuredInputSNR;

            outputSNRdB(experimentCounter) = ...
                currentOutputSNR;

            snrImprovementdB(experimentCounter) = ...
                currentSNRImprovement;

            sampleRate(experimentCounter) = ...
                targetFs;

            cleanPath(experimentCounter) = ...
                relativePath( ...
                currentCleanFile, ...
                projectDir);

            noisyPath(experimentCounter) = ...
                relativePath( ...
                currentNoisyFile, ...
                projectDir);

            wienerPath(experimentCounter) = ...
                relativePath( ...
                currentWienerFile, ...
                projectDir);

            fprintf( ...
                '  measured input = %.2f dB\n', ...
                measuredInputSNR);

            fprintf( ...
                '  output SNR     = %.2f dB\n', ...
                currentOutputSNR);

            fprintf( ...
                '  improvement    = %+.2f dB\n', ...
                currentSNRImprovement);

        end

    end

end

%% ============================================================
%  8. Trim arrays in case any clean file was skipped
% =============================================================

validRows = ...
    strlength(experimentID) > 0;

experimentID = experimentID(validRows);
speakerID = speakerID(validRows);
utteranceID = utteranceID(validRows);
noiseType = noiseType(validRows);

targetSNRdB = targetSNRdB(validRows);
measuredInputSNRdB = measuredInputSNRdB(validRows);
outputSNRdB = outputSNRdB(validRows);
snrImprovementdB = snrImprovementdB(validRows);

sampleRate = sampleRate(validRows);

cleanPath = cleanPath(validRows);
noisyPath = noisyPath(validRows);
wienerPath = wienerPath(validRows);

frameLengthColumn = frameLengthColumn(validRows);
hopLengthColumn = hopLengthColumn(validRows);
fftLengthColumn = fftLengthColumn(validRows);
gainFloorColumn = gainFloorColumn(validRows);
smoothingAlphaColumn = smoothingAlphaColumn(validRows);

%% ============================================================
%  9. Create metadata table
% =============================================================

metadata = table( ...
    experimentID, ...
    speakerID, ...
    utteranceID, ...
    noiseType, ...
    targetSNRdB, ...
    measuredInputSNRdB, ...
    outputSNRdB, ...
    snrImprovementdB, ...
    sampleRate, ...
    frameLengthColumn, ...
    hopLengthColumn, ...
    fftLengthColumn, ...
    gainFloorColumn, ...
    smoothingAlphaColumn, ...
    cleanPath, ...
    noisyPath, ...
    wienerPath, ...
    'VariableNames', { ...
    'experiment_id', ...
    'speaker_id', ...
    'utterance_id', ...
    'noise_type', ...
    'target_snr_db', ...
    'measured_input_snr_db', ...
    'output_snr_db', ...
    'snr_improvement_db', ...
    'sample_rate_hz', ...
    'frame_length', ...
    'hop_length', ...
    'fft_length', ...
    'gain_floor', ...
    'smoothing_alpha', ...
    'clean_path', ...
    'noisy_path', ...
    'wiener_path'});

%% ============================================================
%  10. Save metadata CSV
% =============================================================

metadataFile = ...
    fullfile( ...
    mixtureDir, ...
    'mixture_metadata.csv');

writetable( ...
    metadata, ...
    metadataFile);

%% ============================================================
%  11. Save simple SNR summary
% =============================================================

summaryTable = groupsummary( ...
    metadata, ...
    {'noise_type', 'target_snr_db'}, ...
    {'mean', 'std'}, ...
    {'output_snr_db', 'snr_improvement_db'});

writetable( ...
    summaryTable, ...
    fullfile( ...
    mixtureDir, ...
    'snr_summary.csv'));

%% ============================================================
%  12. Display final summary
% =============================================================

fprintf('\n');
fprintf('====================================================\n');
fprintf('CONTROLLED DATASET GENERATION COMPLETE\n');
fprintf('====================================================\n');

fprintf( ...
    'Generated experiments: %d\n', ...
    height(metadata));

fprintf( ...
    'Metadata file:\n  %s\n', ...
    metadataFile);

fprintf('\nFirst 10 metadata rows:\n');

disp(metadata( ...
    1:min(10, height(metadata)), ...
    {'experiment_id', ...
     'utterance_id', ...
     'noise_type', ...
     'target_snr_db', ...
     'measured_input_snr_db', ...
     'output_snr_db', ...
     'snr_improvement_db'}));

fprintf('\nSNR summary:\n');
disp(summaryTable);

fprintf('\nExpected experiment count = 32.\n');

if height(metadata) == 32
    fprintf('STATUS: PASS - exactly 32 experiments generated.\n');
else
    fprintf( ...
        'STATUS: CHECK - generated %d experiments.\n', ...
        height(metadata));
end

fprintf('====================================================\n');

end


%% ============================================================
%  Fixed student-developed Wiener enhancer
% =============================================================

function enhanced = fixedWienerEnhance( ...
    noisy, ...
    fs, ...
    frameLength, ...
    hopLength, ...
    fftLength, ...
    noiseEstimateStart, ...
    noiseEstimateEnd, ...
    gainFloor, ...
    smoothingAlpha)

noisy = noisy(:);

analysisWindow = ...
    hann(frameLength, 'periodic');

%% ------------------------------------------------------------
% Padding for stable overlap-add reconstruction
% -------------------------------------------------------------

prePad = frameLength;
postPad = frameLength;

x = [
    zeros(prePad, 1);
    noisy;
    zeros(postPad, 1)
];

numFrames = ceil( ...
    (length(x) - frameLength) ...
    / hopLength) + 1;

requiredLength = ...
    (numFrames - 1) ...
    * hopLength ...
    + frameLength;

if requiredLength > length(x)

    x = [
        x;
        zeros( ...
        requiredLength - length(x), ...
        1)
    ];

end

%% ------------------------------------------------------------
% STFT
% -------------------------------------------------------------

X = zeros(fftLength, numFrames);

frameTimes = zeros(1, numFrames);

for k = 1:numFrames

    startIndex = ...
        (k - 1) * hopLength + 1;

    frame = ...
        x( ...
        startIndex : ...
        startIndex + frameLength - 1);

    X(:, k) = ...
        fft( ...
        frame .* analysisWindow, ...
        fftLength);

    centreSample = ...
        startIndex - 1 ...
        + frameLength / 2 ...
        - prePad;

    frameTimes(k) = ...
        centreSample / fs;

end

%% ------------------------------------------------------------
% Practical noise PSD estimate
% -------------------------------------------------------------

noiseFrames = ...
    frameTimes >= noiseEstimateStart ...
    & frameTimes <= noiseEstimateEnd;

if sum(noiseFrames) < 3
    error( ...
        'Insufficient initial noise-only frames.');
end

noisePSD = ...
    mean( ...
    abs(X(:, noiseFrames)).^2, ...
    2);

%% ------------------------------------------------------------
% Wiener filtering
% -------------------------------------------------------------

Y = zeros(size(X));

previousGain = ...
    ones(fftLength, 1);

for k = 1:numFrames

    noisyPSD = ...
        abs(X(:, k)).^2;

    estimatedSpeechPSD = ...
        max( ...
        noisyPSD - noisePSD, ...
        0);

    currentGain = ...
        estimatedSpeechPSD ./ ...
        (estimatedSpeechPSD ...
        + noisePSD ...
        + eps);

    % Fixed gain floor
    currentGain = ...
        max( ...
        currentGain, ...
        gainFloor);

    % Fixed temporal smoothing
    smoothedGain = ...
        smoothingAlpha ...
        * previousGain ...
        + (1 - smoothingAlpha) ...
        * currentGain;

    Y(:, k) = ...
        smoothedGain .* X(:, k);

    previousGain = ...
        smoothedGain;

end

%% ------------------------------------------------------------
% Weighted overlap-add reconstruction
% -------------------------------------------------------------

reconstructed = ...
    zeros(length(x), 1);

windowWeight = ...
    zeros(length(x), 1);

for k = 1:numFrames

    startIndex = ...
        (k - 1) * hopLength + 1;

    frame = ...
        real( ...
        ifft( ...
        Y(:, k), ...
        fftLength));

    frame = ...
        frame(1:frameLength);

    frame = ...
        frame .* analysisWindow;

    outputIndices = ...
        startIndex : ...
        startIndex + frameLength - 1;

    reconstructed(outputIndices) = ...
        reconstructed(outputIndices) ...
        + frame;

    windowWeight(outputIndices) = ...
        windowWeight(outputIndices) ...
        + analysisWindow.^2;

end

validWeight = ...
    windowWeight > 1e-8;

reconstructed(validWeight) = ...
    reconstructed(validWeight) ...
    ./ windowWeight(validWeight);

reconstructed(~validWeight) = 0;

%% ------------------------------------------------------------
% Remove padding
% -------------------------------------------------------------

enhanced = ...
    reconstructed( ...
    prePad + 1 : ...
    prePad + length(noisy));

enhanced = ...
    real(enhanced(:));

enhanced(~isfinite(enhanced)) = 0;

end


%% ============================================================
%  Make project-relative path for CSV portability
% =============================================================

function rel = relativePath(fullPath, projectDir)

fullPath = string(fullPath);
projectDir = string(projectDir);

prefix = projectDir + filesep;

rel = erase( ...
    fullPath, ...
    prefix);

% Use forward slashes so Python can also read paths easily
rel = replace( ...
    rel, ...
    "\", ...
    "/");

end